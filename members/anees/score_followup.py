"""Score the follow-up question runs (N3) written by run_followup.py.

    python members/anees/score_followup.py

Reads every results/restorekv/followup/*.jsonl file and writes followup_summary.json
and FOLLOWUP.md next to them. Scores are task-macro averages (x100) over the four
tasks, separately for the first and the second question of each document. Each
compressed run is compared with the full cache on the same documents, using a 95%
paired bootstrap interval: documents are resampled within each task, 2000 draws.
"""

import glob
import json
import random
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DIR = REPO / "results" / "restorekv" / "followup"
DRAWS, SEED = 2000, 0
NAMES = {"none": "Full cache", "snapkv": "SnapKV", "kvzip": "KVzip", "restorekv": "RestoreKV"}
SETTINGS = {"doc": "Document compressed alone", "q1": "Document + question 1 compressed"}


def load(path):
    rows = [json.loads(line) for line in open(path) if line.strip()]
    return {(r["doc_id"], r["setting"]): r for r in rows}


def macro(rows, keys, q):
    by = defaultdict(list)
    for k in keys:
        by[rows[k]["task"]].append(100 * rows[k]["scores"][q])
    return sum(sum(v) / len(v) for v in by.values()) / len(by)


def paired_ci(run, base, by_task, q):
    rng = random.Random(SEED)
    diffs = []
    for _ in range(DRAWS):
        d = []
        for keys in by_task.values():
            pick = [rng.choice(keys) for _ in keys]
            d.append(100 * sum(run[k]["scores"][q] - base[k]["scores"][q] for k in pick) / len(pick))
        diffs.append(sum(d) / len(d))
    diffs.sort()
    return diffs[int(0.025 * DRAWS)], diffs[int(0.975 * DRAWS) - 1]


def main():
    runs = {Path(f).stem.split("Instruct_")[1]: load(f) for f in sorted(glob.glob(str(DIR / "*.jsonl")))}
    base = runs.pop("none_0.0")
    out, md = {}, ["# Follow-up questions on one compressed cache", "",
                   f"Generated by `members/anees/score_followup.py`. {len(base) // 2} documents with two questions "
                   "(narrativeqa, qasper, multifieldqa_en, qmsum); the cache is compressed once and both questions "
                   "are answered from it. Task-macro scores; Δ vs full cache with a 95% paired bootstrap interval.", "",
                   "The documents come from the whole processed set, so some questions fall in the held-out test "
                   "split (65 of 250 at the time of writing). Nothing was tuned on these runs; DATA 298B test-set "
                   "numbers should leave these documents out or be read with this in mind.", ""]
    for setting, title in SETTINGS.items():
        keys = [k for k in base if k[1] == setting]
        by_task = defaultdict(list)
        for k in keys:
            by_task[base[k]["task"]].append(k)
        if any(set(keys) - set(r) for r in runs.values()):
            raise SystemExit(f"a run is missing documents for setting {setting}")
        full = [macro(base, keys, q) for q in (0, 1)]
        out[setting] = {"documents": len(keys), "full_cache": {"q1": full[0], "q2": full[1]}}
        md += [f"## {title}", "", "| Method | Ratio | Question 1 | Δ [95% CI] | Question 2 | Δ [95% CI] |",
               "|---|---|---|---|---|---|", f"| Full cache | — | {full[0]:.2f} | | {full[1]:.2f} | |"]
        for name, rows in runs.items():
            press, ratio = name.rsplit("_", 1)
            res = {}
            for q in (0, 1):
                score = macro(rows, keys, q)
                res[f"q{q + 1}"] = {"score": score, "delta": score - full[q], "ci": list(paired_ci(rows, base, by_task, q))}
            out[setting][name] = res
            md.append(f"| {NAMES.get(press, press)} | {ratio} | " + " | ".join(
                f"{res[q]['score']:.2f} | {res[q]['delta']:+.2f} [{res[q]['ci'][0]:+.2f}, {res[q]['ci'][1]:+.2f}]"
                for q in ("q1", "q2")) + " |")
        md.append("")
    json.dump(out, open(DIR / "followup_summary.json", "w"), indent=1)
    (DIR / "FOLLOWUP.md").write_text("\n".join(md))
    print("\n".join(md))


if __name__ == "__main__":
    main()
