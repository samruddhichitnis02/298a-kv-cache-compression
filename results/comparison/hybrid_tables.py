"""Tables for review point 1: hybrid eviction + quantization at matched measured bytes.

    python results/comparison/hybrid_tables.py

Reads the hybrid runs in results/hybrid/longbench (400 records, 25 per task), the baseline full-cache
run, and the TurboQuant and ResidualKV runs, all restricted to the same 400 records. Writes
results/comparison/HYBRID.md. Differences are paired over records, with a 95% bootstrap interval
resampled within each task (2,000 resamples, fixed seed).
"""

import json
import random
from collections import defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
HYBRID = REPO / "results/hybrid/longbench"
MODEL = "Llama-3.1-8B-Instruct_"
CATEGORIES = {
    "Single-doc QA": ["narrativeqa", "qasper", "multifieldqa_en"],
    "Multi-doc QA": ["hotpotqa", "2wikimqa", "musique"],
    "Summarization": ["gov_report", "qmsum", "multi_news"],
    "Few-shot": ["trec", "triviaqa", "samsum"],
    "Synthetic": ["passage_count", "passage_retrieval_en"],
    "Code": ["lcc", "repobench-p"],
}
METHODS = [("kvzip", "KVzip"), ("restorekv", "RestoreKV"), ("snapkv", "SnapKV"), ("triattention", "TriAttention")]
# Earlier 800-record runs of the two methods that quantize without evicting; memory is the calculated
# share recorded in results/comparison/comparison.json.
REFERENCE = [("TurboQuant, MSE 2.5-bit", "members/vedant/results/sem1/fixed/Llama-3.1-8B-Instruct_turboquant_mse_2.5bit_0.0.jsonl"),
             ("TurboQuant, MSE 3-bit", "members/vedant/results/sem1/fixed/Llama-3.1-8B-Instruct_turboquant_mse_3bit_0.0.jsonl"),
             ("ResidualKV, ratio 0.9", "results/residualkv/longbench/Llama-3.1-8B-Instruct_residualkv_0.9.jsonl")]


def load(path):
    return {r["record_id"]: r for r in map(json.loads, open(path)) if not r.get("oom")}


def by_task(run, ids):
    tasks = defaultdict(list)
    for i in ids:
        tasks[run[i]["task"]].append(run[i]["score"])
    return {t: 100 * sum(v) / len(v) for t, v in tasks.items()}


def macro(run, ids):
    scores = by_task(run, ids)
    return sum(scores.values()) / len(scores)


def share(run, ids):
    return 100 * sum(run[i]["document_cache_share_measured"] for i in ids) / len(ids)


def paired(a, b, ids, resamples=2000):
    """Macro-average difference a - b with a 95% interval, resampling records within each task."""
    tasks = defaultdict(list)
    for i in ids:
        tasks[a[i]["task"]].append(a[i]["score"] - b[i]["score"])
    diff = lambda sample: 100 * sum(sum(v) / len(v) for v in sample.values()) / len(sample)
    rng = random.Random(0)
    draws = sorted(diff({t: [rng.choice(v) for _ in v] for t, v in tasks.items()}) for _ in range(resamples))
    return diff(tasks), draws[int(0.025 * resamples)], draws[int(0.975 * resamples) - 1]


def signed(triple):
    return f"{triple[0]:+.2f} ({triple[1]:+.2f} to {triple[2]:+.2f})"


def main():
    runs = {p.stem.replace(MODEL, ""): load(p) for p in sorted(HYBRID.glob("*.jsonl"))}
    ids = sorted(set.intersection(*(set(r) for r in runs.values())))
    full = load(REPO / "results/longbench" / f"{MODEL}none_0.0.jsonl")
    assert all(i in full for i in ids)
    memory = {r["source"]: r["memory_pct"] for r in json.load(open(REPO / "results/comparison/comparison.json"))["runs"]}
    full_score = macro(full, ids)

    md = ["# Hybrid eviction + quantization at matched measured bytes", "",
          f"Generated by `results/comparison/hybrid_tables.py`. {len(ids)} LongBench validation records, 25 per task, "
          f"the same records in every row. Uncompressed model on these records: **{full_score:.2f}**.",
          "Cache size is measured from the tensors the packed cache holds, as a share of the full document cache. "
          "Intervals are 95%, paired over records.", "",
          "## One byte budget, three ways to spend it", "",
          "| Method | Eviction only | Evict + 4-bit | Evict + 2-bit | Best hybrid minus eviction only | Best hybrid minus full cache |",
          "|---|---|---|---|---|---|"]
    best = {}
    for key, name in METHODS:
        e, h4, h2 = (runs[f"{key}_budget0.1_pack{b}"] for b in (16, 4, 2))
        top = max((h4, h2), key=lambda r: macro(r, ids))
        best[name] = (e, top)
        md.append(f"| {name} | {macro(e, ids):.2f} | {macro(h4, ids):.2f} | {macro(h2, ids):.2f} | "
                  f"{signed(paired(top, e, ids))} | {signed(paired(top, full, ids))} |")
    e, h = runs["rdkv_0.9_bits0-16_packed"], runs["rdkv_0.9_packed"]
    best["RDKV"] = (e, h)
    md += [f"| RDKV | {macro(e, ids):.2f} | mixed bit-widths: {macro(h, ids):.2f} | | {signed(paired(h, e, ids))} | "
           f"{signed(paired(h, full, ids))} |", "",
           "Measured size of each run:", "", "| Run | Tokens dropped | Measured cache |", "|---|---|---|"]
    for name, run in runs.items():
        dropped = [run[i].get("eviction_ratio") for i in ids if run[i].get("eviction_ratio") is not None]
        md.append(f"| `{name}` | {f'{100 * sum(dropped) / len(dropped):.0f}%' if dropped else 'n/a'} | {share(run, ids):.2f}% |")

    md += ["", "## Against quantization with nothing dropped", "",
           "| Setting | Cache size | Score | Minus full cache |", "|---|---|---|---|"]
    table = [(share(runs["none_0.0_pack4"], ids), "4-bit, nothing dropped (measured)", runs["none_0.0_pack4"]),
             (share(runs["none_0.0_pack2"], ids), "2-bit, nothing dropped (measured)", runs["none_0.0_pack2"]),
             (share(runs["kvzip_budget0.1_pack4"], ids), "KVzip, evict + 4-bit (measured)", runs["kvzip_budget0.1_pack4"]),
             (share(runs["restorekv_budget0.1_pack4"], ids), "RestoreKV, evict + 4-bit (measured)", runs["restorekv_budget0.1_pack4"])]
    table += [(memory[source], f"{name} (calculated, earlier run)", load(REPO / source)) for name, source in REFERENCE]
    for size, name, run in sorted(table, key=lambda row: row[0]):
        md.append(f"| {name} | {size:.1f}% | {macro(run, ids):.2f} | {signed(paired(run, full, ids))} |")
    md.append(f"| Uncompressed | 100.0% | {full_score:.2f} | |")

    md += ["", "## By task type: eviction only, then the best hybrid, at 10% measured memory", "",
           "| Method | " + " | ".join(CATEGORIES) + " |", "|---|" + "---|" * len(CATEGORIES)]
    cats = lambda run: {c: sum(by_task(run, ids)[t] for t in ts) / len(ts) for c, ts in CATEGORIES.items()}
    md.append("| Uncompressed | " + " | ".join(f"{v:.1f}" for v in cats(full).values()) + " |")
    for name, (e, h) in best.items():
        ce, ch = cats(e), cats(h)
        md.append(f"| {name} | " + " | ".join(f"{ce[c]:.1f} → {ch[c]:.1f}" for c in CATEGORIES) + " |")

    out = REPO / "results/comparison/HYBRID.md"
    out.write_text("\n".join(md) + "\n", encoding="utf-8")
    print(out.read_text())


if __name__ == "__main__":
    main()
